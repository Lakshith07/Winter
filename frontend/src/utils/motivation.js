/**
 * Gets quote for a specific challenge day number (1..90)
 */
export function getQuoteForDay(dayNumber) {
  const clampedDay = Math.max(1, Math.min(90, dayNumber || 1));
  return DAILY_QUOTES.find(q => q.day === clampedDay) || DAILY_QUOTES[0];
}

/**
 * Dynamic contextual motivational message engine based on actual user data
 */
export function getContextualMotivation({
  challengeStatus,
  currentStreak,
  todayCompletedCount,
  yesterdayCompletedCount = 0,
  threshold = 6,
  elapsedDaysCount = 1
}) {
  if (challengeStatus === 'before') {
    return {
      title: "The Preparation Phase",
      message: "Your Winter Arc begins October 1, 2026. Prepare your mind, prime your environment, eliminate distractions. 90 days to become unrecognizable.",
      tone: "preparation",
      badge: "Pre-Challenge"
    };
  }

  if (challengeStatus === 'completed') {
    return {
      title: "Mission Accomplished",
      message: "You conquered the 90-day Winter Arc. You showed up, built unbreakable discipline, and transformed your mind and body. Stand proud.",
      tone: "victory",
      badge: "Completed"
    };
  }

  // Today completed all 8 habits!
  if (todayCompletedCount === 8) {
    return {
      title: "Flawless Execution Today",
      message: "You showed up for yourself today and completed all 8 habits. That's a clean 100% win. This is how champions are built.",
      tone: "perfect",
      badge: "8/8 Perfect Day"
    };
  }

  // Today met threshold
  if (todayCompletedCount >= threshold) {
    return {
      title: "Successful Day Logged",
      message: `Great discipline today! With ${todayCompletedCount}/8 habits checked, your streak is secured. Finish strong.`,
      tone: "success",
      badge: "Target Met"
    };
  }

  // High streak milestones
  if (currentStreak >= 30) {
    return {
      title: "30+ Days of Iron Will",
      message: `${currentStreak} days of relentless effort. Look at what consistency can do. You are not the same person who started on Day 1.`,
      tone: "milestone",
      badge: `${currentStreak} Day Streak`
    };
  }

  if (currentStreak >= 7) {
    return {
      title: "One Week of Showing Up",
      message: `${currentStreak} consecutive days of discipline. Your habits are solidifying into permanent character traits. Keep pushing.`,
      tone: "milestone",
      badge: "7+ Days Strong"
    };
  }

  if (currentStreak >= 3) {
    return {
      title: "Three Days of Consistency",
      message: "Three days of showing up. The initial inertia is broken. Keep building momentum one habit at a time.",
      tone: "streak",
      badge: "3 Days Consistent"
    };
  }

  // Streak reset / low streak
  if (currentStreak === 0 && elapsedDaysCount > 1) {
    return {
      title: "Reset & Refocus",
      message: "Your streak is just a number. Your progress and work are bigger than that. Lock in today, complete your habits, and ignite a new streak.",
      tone: "rebound",
      badge: "New Day, New Streak"
    };
  }

  // Default day kickoff
  return {
    title: "Day 1 of the Rest of Your Life",
    message: "Your Winter Arc is in motion. 90 Days. No Excuses. Take the first step and check off your first habit.",
    tone: "kickoff",
    badge: "Day 01"
  };
}
